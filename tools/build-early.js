#!/usr/bin/env node
/**
 * Starts each page's main backend request from the <head> (owner, 12 Nov
 * 2026: the site scan found it otherwise left only after every page script had
 * downloaded and run - about 0.5s in on 4G, 2.5-3s in on a slow connection).
 *
 * Writes a small inline script between the markers
 *   <!-- early-fetch -->  ...  <!-- /early-fetch -->
 * into index.html, store.html and product.html. It asks for the same thing
 * the page's own script asks for a moment later (home.js, store.js,
 * product-page.js), and Api.get (api.js) uses that answer instead of asking
 * again. The backend address is copied from assets/js/config.js, so config.js
 * stays the one place to change it.
 *
 *   node tools/build-early.js          write the blocks
 *   node tools/build-early.js --check  exit 1 if a block is stale
 */
const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const CHECK = process.argv.includes('--check');

// What each page asks for first: [action, params]. Must match the page's own
// Api.get call exactly, or the early answer is simply not used.
const PAGES = {
  'index.html': "asks.push(['getHomePageData', {}]);",
  'store.html': "var s = q.get('store'); if (s) asks.push(['listProducts', { storeSlug: s }]);",
  'product.html': "var s = q.get('store'), p = q.get('product'); if (s && p) asks.push(['getProduct', { storeSlug: s, productId: p }]);"
};

const config = fs.readFileSync(path.join(ROOT, 'assets/js/config.js'), 'utf8');
const m = config.match(/APPS_SCRIPT_URL:\s*'([^']*)'/);
if (!m) { console.error('build-early: APPS_SCRIPT_URL not found in assets/js/config.js'); process.exit(1); }
const API = m[1];

function block(ask) {
  return [
    '<!-- early-fetch -->',
    '  <!-- GENERATED by tools/build-early.js from assets/js/config.js - do not edit here.',
    '       Starts this page\'s main backend request before the page scripts have',
    '       loaded; Api.get (api.js) picks the answer up instead of asking again. -->',
    '  <script>',
    '    (function () {',
    '      try {',
    '        var API = ' + JSON.stringify(API) + ';',
    "        if (window.__mwkRedirecting || !API || API.indexOf('PASTE_YOUR') === 0 || !window.fetch) return;",
    '        var q = new URLSearchParams(location.search), asks = [], early = window.__mwkEarly = {};',
    '        ' + ask,
    '        asks.forEach(function (a) {',
    "          var u = new URL(API); u.searchParams.set('action', a[0]);",
    '          Object.keys(a[1]).forEach(function (k) { u.searchParams.set(k, a[1][k]); });',
    "          early[a[0] + '|' + JSON.stringify(a[1])] = fetch(u.toString(), { method: 'GET' })",
    '            .then(function (r) { return r.json(); }).catch(function () { return null; });',
    '        });',
    '      } catch (e) { /* the page asks for itself as before */ }',
    '    })();',
    '  </script>',
    '  <!-- /early-fetch -->'
  ].join('\n');
}

let stale = 0;
for (const [page, ask] of Object.entries(PAGES)) {
  const file = path.join(ROOT, page);
  const html = fs.readFileSync(file, 'utf8');
  const re = /<!-- early-fetch -->[\s\S]*?<!-- \/early-fetch -->/;
  if (!re.test(html)) { console.error(page + ': no <!-- early-fetch --> marker'); stale++; continue; }
  const built = html.replace(re, block(ask));
  if (built === html) continue;
  if (CHECK) { console.error(page + ': early-fetch block is out of date. Run `npm run build`.'); stale++; }
  else { fs.writeFileSync(file, built); console.log('  built early-fetch in ' + page); }
}
if (CHECK) {
  if (stale) process.exit(1);
  console.log('early-fetch blocks match config.js.');
}
