#!/usr/bin/env node
/**
 * Copies the listing rules engine (apps-script/ListingRules.gs) to
 * assets/js/listing-rules.js, so the seller's product form runs exactly the
 * rules the backend runs. One source: edit the .gs, then `npm run build`.
 *
 *   node tools/build-listing-rules.js          write the copy
 *   node tools/build-listing-rules.js --check  exit 1 if the copy is stale
 */
const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const SRC = path.join(ROOT, 'apps-script', 'ListingRules.gs');
const DEST = path.join(ROOT, 'assets', 'js', 'listing-rules.js');
const HEADER = '// GENERATED by tools/build-listing-rules.js from apps-script/ListingRules.gs - do not edit here.\n';

const built = HEADER + fs.readFileSync(SRC, 'utf8');
const existing = fs.existsSync(DEST) ? fs.readFileSync(DEST, 'utf8') : null;
if (process.argv.includes('--check')) {
  if (existing !== built) {
    console.error('assets/js/listing-rules.js is out of date. Run `npm run build`.');
    process.exit(1);
  }
  console.log('listing-rules.js matches ListingRules.gs.');
} else if (existing !== built) {
  fs.writeFileSync(DEST, built);
  console.log('  built assets/js/listing-rules.js');
}
